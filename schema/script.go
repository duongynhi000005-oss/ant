package schema

import (
	"fmt"
	"strings"
)

// Generated is the first line of a generated migration.
const Generated = "-- Generated by ant from your models. This is plain SQL: review it, and edit it if you need to."

// NoTransaction is the directive that makes a migration run outside a transaction.
const NoTransaction = "-- ant:no-transaction"

// Backfill fills AddColumn.Backfill on changes that need it, with the dialect's
// zero value. Go gives every field a zero value, so this is the value a new
// column has in a struct that was loaded before the column existed.
func Backfill(d Dialect, p *Plan) {
	for i, c := range p.Changes {
		add, ok := c.(AddColumn)
		if !ok || add.Column.Nullable || add.Column.Default != "" || add.Column.Identity ||
			add.Column.Generated != "" {
			continue
		}

		add.Backfill = d.Zero(add.Column.Type)
		p.Changes[i] = add
	}
}

// Statements returns the SQL of a plan, without comments.
func Statements(d Dialect, p *Plan) ([]string, error) {
	var out []string

	for _, c := range p.Changes {
		statements, err := d.Statements(c)
		if err != nil {
			return nil, err
		}

		out = append(out, statements...)
	}

	return out, nil
}

// Script writes a plan as a SQL file, with warnings as comments above the
// statements they concern.
func Script(d Dialect, p *Plan) (string, error) {
	var b strings.Builder
	b.WriteString(Generated + "\n")

	if p.Online() {
		b.WriteString(NoTransaction + "\n")

		b.WriteString(
			"-- WARNING: a statement below cannot run in a transaction, so this file runs without one.\n",
		)

		b.WriteString(
			"-- If it fails partway, finish it by hand. Consider keeping such statements in a file of their own.\n",
		)
	}

	for _, hint := range p.Hints {
		rename, err := d.Statements(hint.Change())
		if err != nil {
			return "", err
		}

		fmt.Fprintf(&b, "\n-- WARNING: %s. If this is a rename, keep the data by\n", hint)
		b.WriteString("-- replacing the drop and add below with:\n")

		for _, statement := range rename {
			fmt.Fprintf(&b, "--   %s;\n", statement)
		}
	}

	for _, c := range p.Changes {
		statements, err := d.Statements(c)
		if err != nil {
			return "", err
		}

		b.WriteByte('\n')

		if w := c.Warning(); w != "" {
			fmt.Fprintf(&b, "-- WARNING: %s\n", w)
		}

		for _, statement := range statements {
			b.WriteString(statement + ";\n")
		}
	}

	return b.String(), nil
}
